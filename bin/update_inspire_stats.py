#!/usr/bin/env python3
"""Fetch publication statistics from INSPIRE-HEP and write _data/inspire_stats.yml.

The numbers (h-index, publication count, citation count) are shown on the
publications page via _includes/inspire_stats.html.  This script is
run on a schedule by .github/workflows/update-publications.yml, but can also be run by
hand from the repository root:

    python3 bin/update_inspire_stats.py

Only the standard library is used.  The output file is left untouched when the
numbers have not changed, so that the "updated" date reflects the last change
rather than the last run.
"""

import datetime
import json
import pathlib
import sys
import urllib.parse
import urllib.request

# INSPIRE author identifier (BAI) for Max Isi: https://inspirehep.net/authors/1275240
AUTHOR = "Maximiliano.Isi.1"

# Search queries in INSPIRE syntax.  The second one excludes LIGO-Virgo-KAGRA
# collaboration papers by removing anything with the alphabetically-first
# authors of the collaboration author lists ("Abbott", "Abac").
QUERIES = {
    "all": f"a {AUTHOR}",
    "noncollab": f"a {AUTHOR} - abbott - abac",
}

API = "https://inspirehep.net/api/literature/facets"
WEB = "https://inspirehep.net/literature"
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "_data" / "inspire_stats.yml"
USER_AGENT = "maxisi.github.io stats updater (https://github.com/maxisi/maxisi.github.io)"


def fetch(query):
    """Return publication, search-hit, citation and h-index counts for an INSPIRE query."""
    params = urllib.parse.urlencode({"q": query, "facet_name": "citation-summary"})
    request = urllib.request.Request(f"{API}?{params}", headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=60) as response:
        data = json.load(response)
    summary = data["aggregations"]["citation_summary"]
    citeable = summary["citations"]["buckets"]["all"]
    # "publications" is the number of citeable papers, i.e. the "Citeable papers"
    # row of INSPIRE's citation summary (theses and unrefereed talks are not
    # citeable); "hits" is the raw number of search results, kept for reference.
    return {
        "publications": int(citeable["doc_count"]),
        "hits": int(data["hits"]["total"]["value"]),
        "citations": int(citeable["citations_count"]["value"]),
        "hindex": int(summary["h-index"]["value"]["all"]),
    }


def short(n):
    """Format 118977 -> '119k', 5096 -> '5.1k', 950 -> '950'."""
    if n >= 10_000:
        return f"{round(n / 1000)}k"
    if n >= 1_000:
        return f"{n / 1000:.1f}k"
    return str(n)


def web_url(query):
    params = urllib.parse.urlencode(
        {"sort": "mostrecent", "size": 25, "page": 1, "q": query, "ui-citation-summary": "true"}
    )
    return f"{WEB}?{params}"


def render(stats, updated):
    lines = [
        "# Publication statistics from INSPIRE-HEP.",
        "# Generated by bin/update_inspire_stats.py -- do not edit by hand.",
        f"updated: {updated}",
    ]
    for key, query in QUERIES.items():
        s = stats[key]
        lines += [
            f"{key}:",
            f"  query: {json.dumps(query)}",
            f"  url: {json.dumps(web_url(query))}",
            f"  publications: {s['publications']}",
            f"  hits: {s['hits']}",
            f"  citations: {s['citations']}",
            f"  citations_short: {json.dumps(short(s['citations']))}",
            f"  hindex: {s['hindex']}",
        ]
    return "\n".join(lines) + "\n"


def strip_date(text):
    return "\n".join(line for line in text.splitlines() if not line.startswith("updated:"))


def main():
    stats = {}
    for key, query in QUERIES.items():
        try:
            stats[key] = fetch(query)
        except Exception as error:  # noqa: BLE001 -- report and fail loudly
            sys.exit(f"error: could not fetch INSPIRE stats for {query!r}: {error}")
        print(f"{key:10s} {stats[key]}")

    today = datetime.date.today().isoformat()
    new = render(stats, today)
    old = OUTPUT.read_text() if OUTPUT.exists() else ""
    if strip_date(old) == strip_date(new):
        print(f"{OUTPUT.relative_to(pathlib.Path.cwd())}: unchanged")
        return
    OUTPUT.write_text(new)
    print(f"{OUTPUT.relative_to(pathlib.Path.cwd())}: updated")


if __name__ == "__main__":
    main()
